/**
 * ファイルサイズ制限定数
 *
 * PDFファイルおよび開示情報ファイルのサイズ制限を定義します。
 * これらの定数は、バリデーション、ダウンロード、保存処理で使用されます。
 *
 * Requirements: 要件1.3, 2.3（PDFダウンロード、整合性検証）
 */

/**
 * PDFファイルの最小サイズ（バイト単位）
 *
 * 値: 10KB (10,240バイト)
 *
 * 根拠:
 * - 有効なPDFファイルは最低でもヘッダー、カタログ、ページオブジェクトを含む必要がある
 * - 10KB未満のPDFは不完全またはダミーファイルの可能性が高い
 * - TDnetの開示情報PDFは通常数百KB以上のサイズを持つ
 */
export const MIN_PDF_SIZE = 10 * 1024; // 10KB

/**
 * PDFファイルの最大サイズ（バイト単位）
 *
 * 値: 50MB (52,428,800バイト)
 *
 * 根拠:
 * - Lambda関数のメモリ制約（最大512MB）を考慮
 * - TDnetの開示情報PDFは通常数MB程度
 * - 50MBを超えるPDFは異常または不正なファイルの可能性が高い
 * - S3への保存とDynamoDBへのメタデータ保存のバランスを考慮
 */
export const MAX_PDF_SIZE = 50 * 1024 * 1024; // 50MB

/**
 * 開示情報ファイルの最大サイズ（バイト単位）
 *
 * 値: 100MB (104,857,600バイト)
 *
 * 根拠:
 * - PDFファイル以外の添付ファイル（Excel、Zipなど）を考慮
 * - Lambda関数のメモリ制約（最大512MB）を考慮
 * - DynamoDBのアイテムサイズ制限（400KB）を超えるファイルはS3に保存
 * - 100MBを超えるファイルは異常または不正なファイルの可能性が高い
 */
export const MAX_FILE_SIZE = 100 * 1024 * 1024; // 100MB
